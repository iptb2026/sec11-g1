<template>
  <q-page class="q-pa-md">
    <div class="row items-center q-mb-md">
      <div class="text-h5">Interbank Transfers</div>
      <q-space />
      <q-btn color="primary" icon="add" label="New" @click="openCreate" />
    </div>

    <q-table :rows="rows" :columns="columns" row-key="id" :loading="loading" flat bordered>
      <template #body-cell-actions="props">
        <q-td :props="props">
          <q-btn
            v-if="props.row.status === 'PROCESSING'"
            dense flat round icon="check_circle" color="positive"
            title="Mark SUCCESS"
            @click="markStatus(props.row, 'SUCCESS')"
          />
          <q-btn
            v-if="props.row.status === 'PROCESSING'"
            dense flat round icon="cancel" color="negative"
            title="Mark FAILED"
            @click="markStatus(props.row, 'FAILED')"
          />
          <!-- No edit: a posted interbank transfer can only change status (see Mark SUCCESS / FAILED). -->
          <q-btn dense flat round icon="delete" color="negative" @click="removeRow(props.row)" />
        </q-td>
      </template>
    </q-table>

    <q-dialog v-model="showDialog">
      <q-card style="width: 460px">
        <q-card-section>
          <div class="text-h6">New Interbank Transfer</div>
        </q-card-section>

        <q-card-section class="q-gutter-md">
          <q-select
            v-model="form.source_account_id"
            label="Source Account"
            filled
            emit-value
            map-options
            :options="accountOptions"
          >
            <template v-slot:option="scope">
              <q-item v-bind="scope.itemProps">
                <q-item-section>
                  <q-item-label>{{ scope.opt.label }}</q-item-label>
                  <q-item-label caption>{{ scope.opt.holder }}</q-item-label>
                </q-item-section>
              </q-item>
            </template>
          </q-select>
          <q-input
            v-if="form.source_account_id"
            :model-value="accountHolderByAccountId[form.source_account_id] || ''"
            label="Account Holder"
            filled
            readonly
          />
          <q-select
            v-model="form.target_bank_id"
            label="Target Bank"
            filled
            emit-value
            map-options
            :options="bankOptions"
          />
          <q-input v-model="form.target_account_number" label="Target Account Number" filled />
          <q-input v-model="form.beneficiary_name" label="Beneficiary Name" filled />
          <!-- Reference number is generated by the backend (IB + date + random). -->
          <q-input v-model.number="form.amount" label="Amount" type="number" filled />
          <q-input v-model.number="form.transfer_fee" label="Transfer Fee" type="number" filled />
        </q-card-section>

        <q-card-actions align="right">
          <q-btn flat label="Cancel" v-close-popup />
          <q-btn color="primary" label="Save" @click="save" />
        </q-card-actions>
      </q-card>
    </q-dialog>
  </q-page>
</template>

<script setup>
import { ref } from 'vue'
import { useQuasar } from 'quasar'
import { useAutoRefresh } from '@/composables/useAutoRefresh'
import api, { errorMessage } from '@/services/api'

const $q = useQuasar()

const columns = [
  { name: 'id', label: 'ID', field: 'id', align: 'left' },
  { name: 'source_account_id', label: 'Source Account ID', field: 'source_account_id', align: 'left' },
  { name: 'source_account_number', label: 'Source Account Number', field: (row) => accountNumberByAccountId.value[row.source_account_id] || '', align: 'left' },
  { name: 'source_account_name', label: 'Source Account Name', field: (row) => accountHolderByAccountId.value[row.source_account_id] || '', align: 'left' },
  { name: 'target_bank_id', label: 'Target Bank', field: (row) => bankOptions.value.find((o) => o.value === row.target_bank_id)?.label || row.target_bank_id, align: 'left' },
  { name: 'reference_number', label: 'Reference', field: 'reference_number', align: 'left' },
  { name: 'amount', label: 'Amount', field: 'amount', align: 'right' },
  { name: 'transfer_fee', label: 'Fee', field: 'transfer_fee', align: 'right' },
  { name: 'status', label: 'Status', field: 'status', align: 'left' },
  { name: 'actions', label: 'Actions', field: 'actions', align: 'right' },
]

const rows = ref([])
const accountOptions = ref([])
const accountHolderByAccountId = ref({})
const accountNumberByAccountId = ref({})
const bankOptions = ref([])
const loading = ref(false)
const showDialog = ref(false)
const emptyForm = () => ({
  source_account_id: null,
  target_bank_id: null,
  target_account_number: '',
  beneficiary_name: '',
  amount: 0,
  transfer_fee: 0,
})
const form = ref(emptyForm())

async function loadRows ({ silent = false } = {}) {
  if (!silent) loading.value = true
  try {
    const { data } = await api.get('/interbank-transfers/')
    rows.value = data
  } catch (err) {
    if (!silent) $q.notify({ type: 'negative', message: errorMessage(err, 'Failed to load data') })
  } finally {
    loading.value = false
  }
}

async function loadOptions () {
  const [{ data: accounts }, { data: users }] = await Promise.all([
    api.get('/accounts/'),
    api.get('/users/'),
  ])

  const nameByUserId = {}
  users.forEach((u) => {
    nameByUserId[u.id] = `${u.first_name} ${u.last_name}`
  })

  accountOptions.value = accounts.map((a) => ({
    label: a.account_number,
    value: a.id,
    holder: nameByUserId[a.customer_id] || '',
  }))
  accountNumberByAccountId.value = Object.fromEntries(accounts.map((a) => [a.id, a.account_number]))
  accountHolderByAccountId.value = Object.fromEntries(
    accounts.map((a) => [a.id, nameByUserId[a.customer_id] || '']),
  )

  const { data: banks } = await api.get('/banks/')
  bankOptions.value = banks.map((b) => ({ label: `${b.bank_code} - ${b.bank_name}`, value: b.id }))
}

// Reloads the table AND the dropdown options, so balances, names, and
// newly added records show up right after any add / edit / delete.
// Also called in the background by useAutoRefresh (silent: no spinner/toasts).
async function refresh ({ silent = false } = {}) {
  try {
    await Promise.all([loadRows({ silent }), loadOptions()])
  } catch (err) {
    if (!silent) $q.notify({ type: 'negative', message: errorMessage(err, 'Failed to load data') })
  }
}

function openCreate () {
  form.value = emptyForm()
  showDialog.value = true
}

async function save () {
  try {
    await api.post('/interbank-transfers/', form.value)
    showDialog.value = false
    $q.notify({ type: 'positive', message: 'Interbank transfer saved' })
    await refresh()
  } catch (err) {
    $q.notify({ type: 'negative', message: errorMessage(err, 'Save failed') })
  }
}

async function markStatus (row, status) {
  try {
    await api.put(`/interbank-transfers/${row.id}/status`, { status })
    $q.notify({ type: 'positive', message: `Marked ${status}` })
    await refresh()
  } catch (err) {
    $q.notify({ type: 'negative', message: errorMessage(err, 'Status update failed') })
  }
}

function removeRow (row) {
  $q.dialog({
    title: 'Confirm Delete',
    message: `Delete interbank transfer "${row.reference_number}"?`,
    cancel: true,
    persistent: true,
  }).onOk(async () => {
    try {
      await api.delete(`/interbank-transfers/${row.id}`)
      $q.notify({ type: 'positive', message: 'Interbank transfer deleted' })
      await refresh()
    } catch (err) {
      $q.notify({ type: 'negative', message: errorMessage(err, 'Delete failed') })
    }
  })
}

useAutoRefresh(refresh)
</script>
